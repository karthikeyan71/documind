-- task-api: local PostgreSQL setup and mock data
-- Run this file against the default "postgres" database.
-- Example:
--   psql -U postgres -d postgres -f setup_tasks.sql
--
-- This script creates task_api_db if it does not already exist.
-- CREATE DATABASE cannot run inside a transaction, so it is handled
-- separately by the psql \gexec command below.

SELECT 'CREATE DATABASE task_api_db'
WHERE NOT EXISTS (
    SELECT 1 FROM pg_database WHERE datname = 'task_api_db'
)\gexec

\connect task_api_db

CREATE TABLE IF NOT EXISTS tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(100) NOT NULL,
    description TEXT,
    priority INTEGER NOT NULL CHECK (priority BETWEEN 1 AND 5),
    status VARCHAR(20) NOT NULL DEFAULT 'todo'
        CHECK (status IN ('todo', 'in_progress', 'completed')),
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Insert mock rows only when the table is empty, so rerunning this file
-- does not duplicate these sample records.
INSERT INTO tasks (title, description, priority, status, completed)
SELECT seed.title, seed.description, seed.priority, seed.status, seed.completed
FROM (
    VALUES
        ('Learn Python', 'Review Python fundamentals and type annotations.', 1, 'in_progress', FALSE),
        ('Learn FastAPI', 'Build REST endpoints and validate request bodies.', 2, 'todo', FALSE),
        ('Connect PostgreSQL', 'Connect the task API to the local database.', 2, 'todo', FALSE),
        ('Add task validation', 'Validate title length and priority range.', 3, 'completed', TRUE),
        ('Write API tests', 'Test task creation, retrieval, and validation errors.', 4, 'todo', FALSE)
) AS seed(title, description, priority, status, completed)
WHERE NOT EXISTS (SELECT 1 FROM tasks);

-- Verify the seeded data.
SELECT id, title, description, priority, status, completed, created_at
FROM tasks
ORDER BY id;
